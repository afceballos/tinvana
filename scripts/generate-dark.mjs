// Generates src/dark.css: dark-theme overrides for light colors hard-coded in the panel stylesheets.
// Run after changing panel CSS: node scripts/generate-dark.mjs. Output is committed.
import {readFileSync,writeFileSync} from 'node:fs';
const files=['style','premium','media','brand','tinvana','builder','orders','media-library','leads','profile','ai','ai-settings','account-access','header-editor','search-select','notifications','landing-form','floating-panel','product-offers'].map(n=>`src/${n}.css`);
const SKIP_SELECTOR=/landing-form|\.ts-|origami|login-intro|app-sidebar|\.primary|brand-entrance|theme-toggle|nav-pill|:root/;
const SKIP_COLOR_SELECTOR=/\.primary|button|pill|badge|status|tag|toast|active|select-button|brand|swatch|dot|chip|alert|notice|error|success|warning|risk|danger|tone|cta/i;

const expand=h=>h.length===4?'#'+[...h.slice(1)].map(c=>c+c).join(''):h.slice(0,7);
const rgb=h=>{const n=parseInt(expand(h).slice(1),16);return [n>>16&255,n>>8&255,n&255];};
const lum=h=>{const [r,g,b]=rgb(h).map(v=>{v/=255;return v<=.03928?v/12.92:((v+.055)/1.055)**2.4;});return .2126*r+.7152*g+.0722*b;};
const sat=h=>{const [r,g,b]=rgb(h);return Math.max(r,g,b)-Math.min(r,g,b);};
const HEX=/#[0-9a-fA-F]{3}(?:[0-9a-fA-F]{3})?\b/g;
const bgVar=h=>lum(h)>.9?'var(--surface)':'var(--soft)';

function* rules(css,wrapper=''){
 let i=0;
 while(i<css.length){
  const open=css.indexOf('{',i);if(open<0)return;
  const head=css.slice(i,open).trim().replace(/\/\*[\s\S]*?\*\//g,'').trim();
  let depth=1,j=open+1;while(j<css.length&&depth){if(css[j]==='{')depth++;else if(css[j]==='}')depth--;j++;}
  const body=css.slice(open+1,j-1);
  if(head.startsWith('@media')||head.startsWith('@supports'))yield* rules(body,head);
  else if(!head.startsWith('@'))yield {selector:head,body,wrapper};
  i=j;
 }
}

const out=new Map();
for(const file of files){
 let css;try{css=readFileSync(file,'utf8').replace(/\/\*[\s\S]*?\*\//g,'');}catch{continue;}
 for(const {selector,body,wrapper} of rules(css)){
  const kept=selector.split(',').map(x=>x.trim()).filter(x=>x&&!SKIP_SELECTOR.test(x));if(!kept.length)continue;
  const decls=[];
  for(const d of body.split(';')){
   const k=d.indexOf(':');if(k<0)continue;const prop=d.slice(0,k).trim().toLowerCase(),value=d.slice(k+1).trim();
   if(/^background(-color)?$/.test(prop)){
    const named=/^(white|#fff|#ffffff)$/i.test(value);const hexes=value.match(HEX)||[];
    if(named)decls.push(`background:var(--surface)`);
    else if(hexes.length===1&&value===hexes[0]&&lum(hexes[0])>.78)decls.push(`background:${bgVar(hexes[0])}`);
    else if(/gradient/.test(value)&&hexes.length&&hexes.every(h=>lum(h)>.78))decls.push(`background:linear-gradient(135deg,var(--surface),var(--soft))`);
   }else if(/^border(-top|-right|-bottom|-left)?(-color)?$/.test(prop)){
    const hexes=(value.match(HEX)||[]).filter(h=>lum(h)>.6&&sat(h)<90);
    if(hexes.length)decls.push(`${prop.includes('color')?prop:prop+'-color'}:var(--line)`);
   }else if(prop==='color'&&!SKIP_COLOR_SELECTOR.test(selector)&&!/background/.test(body)){
    if(HEX.test(value)){HEX.lastIndex=0;const h=value.match(HEX)[0];const l=lum(h);if(l<.07)decls.push('color:var(--ink)');else if(l<.35&&sat(h)<140)decls.push('color:var(--muted)');}
    HEX.lastIndex=0;
   }
  }
  if(!decls.length)continue;
  const sel=kept.map(s=>`:root[data-theme=dark] ${s}`).join(',');
  const rule=`${sel}{${decls.join(';')}}`;
  const key=wrapper||'';out.set(key,[...(out.get(key)||[]),rule]);
 }
}
let text='/* GENERATED by scripts/generate-dark.mjs — do not edit by hand. Dark-theme overrides for hard-coded light colors. */\n';
for(const [wrapper,list] of out){const unique=[...new Set(list)];text+=wrapper?`${wrapper}{\n${unique.join('\n')}\n}\n`:unique.join('\n')+'\n';}
writeFileSync('src/dark.css',text);
console.log('rules:',[...out.values()].reduce((n,l)=>n+new Set(l).size,0));
